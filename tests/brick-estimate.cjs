const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const compiled = ts.transpileModule(fs.readFileSync('lib/brick-estimate.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const model = new Module('brick-estimate');
model._compile(compiled, 'brick-estimate.cjs');
const {estimateHouse, sampleHouse} = model.exports;
const basic = {...sampleHouse,width:10,depth:10,height:10,externalThickness:12,internalLength:0,openings:0,waste:0,joint:.375};
const moduleVolume = 10.375 * 5.375 * 3.375 / 1728;
assert.equal(estimateHouse(basic).quantity, Math.ceil(400 / moduleVolume));
assert.equal(estimateHouse({...basic,floors:2}).quantity, Math.ceil(800 / moduleVolume));
assert.equal(estimateHouse({...basic,openings:25}).quantity, Math.ceil(300 / moduleVolume));
assert.equal(estimateHouse({...basic,waste:10}).quantity, Math.ceil(440 / moduleVolume));
assert.equal(estimateHouse({...basic,internalLength:20,internalThickness:6}).internalVolume,100);
for (const change of [{width:NaN},{depth:0},{floors:1.5},{openings:100},{joint:0},{internalLength:-1},{width:Infinity}]) assert.equal(estimateHouse({...basic,...change}),null);
const sample=estimateHouse(sampleHouse);
assert.equal(sample.area,648);
assert.equal(sample.perimeter,102);
assert.ok(sample.low<=sample.quantity && sample.high>=sample.quantity);
assert.ok(estimateHouse({...sampleHouse,joint:.5}).quantity<sample.quantity);
console.log('Brick estimator checks passed. Sample:',JSON.stringify(sample));
